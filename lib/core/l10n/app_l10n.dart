  static bool get isRtl => _currentLang == 'ar';

  static String normalizeCode(String? code) {
    final c = (code ?? 'fr').trim().toLowerCase();
    if (c.startsWith('en')) return 'en';
    if (c.startsWith('ar')) return 'ar';
    return 'fr';
  }

  static void setLanguage(String? code) {
    _currentLang = normalizeCode(code);
  }

  static String languageDisplayName(String code) {
    switch (normalizeCode(code)) {
      case 'en':
        return 'English';
      case 'ar':
        return 'العربية';
      default:
        return 'Français';
    }
  }

  static String languageBadge(String code) {
    switch (normalizeCode(code)) {
      case 'en':
        return 'EN';
      case 'ar':
        return 'عربي';
      default:
        return 'FR';
    }
  }

  static String t(String key, [Map<String, String>? params]) {
    final map = _translations[_currentLang] ?? _fr;
    var text = map[key] ?? _fr[key] ?? key;
    if (params != null && params.isNotEmpty) {
      params.forEach((k, v) {
        text = text.replaceAll('{$k}', v);
      });
    }
    return text;
  }

